-- # 6 Ranking TOP-N BOTTOM-N
-- Which 5 products generate the highest revenue?
select top 5 
    p.product_name,
    sum(s.sales_amount) as hightest_revenue
from dbo.fact_sales as s
left join dbo.dim_products as p
    on s.product_key = p.product_key
group by p.product_name
order by hightest_revenue desc ;

-- What are the 5 worst-performing products in terms of sales?
select top 5 
    p.product_name,
    sum(s.sales_amount) as hightest_revenue
from dbo.fact_sales as s
left join dbo.dim_products as p
    on s.product_key = p.product_key
group by p.product_name
order by hightest_revenue ;

-- With Window function is more complitate
select *
from (
select 
    p.product_name,
    sum(s.sales_amount) as hightest_revenue,
    ROW_NUMBER() over(order by sum(s.sales_amount) desc) as rank_products
from dbo.fact_sales as s
left join dbo.dim_products as p
    on s.product_key = p.product_key
group by  p.product_name 
) t 
where rank_products < = 5 ;

