-- #5 Magnitude Exploration
-- Find total customers by countries
select 
    country,count(customer_key) as total_customers
from dbo.dim_customers
group by country 
order by total_customers desc ;

-- Find total customers by gender
select 
    gender,count(customer_key) as total_customers_gender
from dbo.dim_customers
group by gender
order by total_customers_gender desc ;

-- Find total products by category
select
    category, count(product_key) as count_product
from dbo.dim_products
group by category
order by count_product desc ;

-- What is the average costs in each category?
select
    category,avg(cost) as avg_cost
from dbo.dim_products
group by category   
order by avg_cost desc ;

-- What is the total revenue generated for each category?
select 
    p.category,
    sum(sales_amount) as sum_sales
from dbo.fact_sales as f
left join dbo.dim_products as p
    on f.product_key = p.product_key
group by p.category
order by sum_sales desc ;

-- Find total revenue is generated by each customer
select 
    c.customer_key,
    c.first_name,
    c.last_name,
    sum(sales_amount) as total_revenue
from dbo.fact_sales as f
left join dbo.dim_customers as c
    on f.customer_key = c.customer_key
group by 
        c.customer_key,
        c.first_name,
        c.last_name
order by total_revenue desc ;
 
-- What is the distribution of sold items across countries?
select 
    c.country,
    sum(f.quantity) as total_sold_items
from dbo.fact_sales as f
left join dbo.dim_customers as c
    on f.customer_key = c.customer_key
group by c.country
order by total_sold_items desc ;
 

