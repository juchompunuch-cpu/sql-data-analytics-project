-- # 4 Measure Exploration
-- Find the total sales
-- Find how many items are sold 
-- Find the averafe selling price
-- Find the total number of orders
-- Find the total number of product
-- Find the total number of customers
-- Find the total number of customers that has placed an order
SELECT 
    SUM(sales_amount) AS TotalSales,
    SUM(quantity) AS TotalItemsSold,
    AVG(price) AS AverageSellingPrice,
    COUNT(DISTINCT order_number) AS TotalOrders,
    COUNT(DISTINCT product_key) AS TotalProducts,
    COUNT(DISTINCT customer_key) AS TotalCustomers,
    COUNT(DISTINCT CASE WHEN customer_key IS NOT NULL THEN customer_key END) AS CustomersWithOrders
FROM 
    dbo.fact_sales;

-- Generate report a report that shoe all key metrics of the business
